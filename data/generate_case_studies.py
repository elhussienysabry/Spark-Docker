#!/usr/bin/env python3
"""Generate deterministic datasets for the four business case studies.

The data is synthetic and intentionally small enough to run on the four-core
Docker lab. It is *not* real customer, network, payment, or shipment data.
The generator is seeded so repeated runs produce the same files.

Usage:
    python3 data/generate_case_studies.py
    python3 data/generate_case_studies.py --output /tmp/spark-data/case_studies

Outputs:
    case_studies/telecom/towers.csv
    case_studies/telecom/network_events.csv
    case_studies/fraud/merchants.csv
    case_studies/fraud/transactions.csv
    case_studies/logistics/hubs.csv
    case_studies/logistics/shipments.csv

The e-commerce case study reuses the existing retail datasets generated by
``data/generate_datasets.py``.
"""

from __future__ import annotations

import argparse
import csv
import math
import random
from datetime import datetime, timedelta
from pathlib import Path

SEED = 2026
N_TELECOM_EVENTS = 36_000
N_TRANSACTIONS = 30_000
N_FRAUD = 600
N_SHIPMENTS = 20_000

# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------


def write_csv(path: Path, header: list[str], rows: list[list[object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)


def weighted(rng: random.Random, pairs: list[tuple[object, float]]) -> object:
    values, weights = zip(*pairs)
    return rng.choices(values, weights=weights, k=1)[0]


def random_ts(rng: random.Random, start: datetime, days: int, hour_weights: list[float] | None = None) -> datetime:
    day = rng.randrange(days)
    if hour_weights is None:
        hour = rng.randrange(24)
    else:
        hour = rng.choices(range(24), weights=hour_weights, k=1)[0]
    return start + timedelta(
        days=day,
        hours=hour,
        minutes=rng.randrange(60),
        seconds=rng.randrange(60),
    )


# ---------------------------------------------------------------------------
# Telecom: cell-site events and tower reference data
# ---------------------------------------------------------------------------

TOWERS = [
    # tower_id, site_name, city, region, technology, capacity_mbps, lat, lon
    ("TWR-001", "Cairo Downtown", "Cairo", "Cairo", "5G", 1200, 30.0444, 31.2357),
    ("TWR-002", "Giza Pyramids", "Giza", "Cairo", "4G", 700, 29.9792, 31.1342),
    ("TWR-003", "Alexandria Corniche", "Alexandria", "Alexandria", "5G", 900, 31.2001, 29.9187),
    ("TWR-004", "New Cairo", "Cairo", "Cairo", "5G", 1000, 30.0300, 31.4700),
    ("TWR-005", "Mansoura Center", "Mansoura", "Delta", "4G", 500, 31.0409, 31.3785),
    ("TWR-006", "Aswan Market", "Aswan", "Upper Egypt", "4G", 350, 24.0889, 32.8998),
    ("TWR-007", "Luxor West", "Luxor", "Upper Egypt", "4G", 300, 25.6872, 32.6396),
    ("TWR-008", "Suez Industrial", "Suez", "Canal", "5G", 800, 29.9668, 32.5498),
]

TELECOM_PLANS = [("Consumer", 0.68), ("Business", 0.24), ("Enterprise", 0.08)]
TELECOM_DEVICES = [("iPhone", 0.28), ("Android", 0.52), ("Router", 0.12), ("IoT", 0.08)]
EVENT_TYPES = [("data", 0.52), ("voice", 0.34), ("sms", 0.14)]


def generate_telecom(rng: random.Random, out: Path) -> None:
    tower_rows = [list(t) for t in TOWERS]
    write_csv(
        out / "telecom" / "towers.csv",
        ["tower_id", "site_name", "city", "region", "technology", "capacity_mbps", "latitude", "longitude"],
        tower_rows,
    )

    # TWR-001 is deliberately hot: it carries more traffic and shows congestion.
    tower_weights = [0.26, 0.17, 0.13, 0.12, 0.10, 0.07, 0.06, 0.09]
    tower_ids = [t[0] for t in TOWERS]
    tower_tech = {t[0]: t[4] for t in TOWERS}
    tower_region = {t[0]: t[3] for t in TOWERS}
    hour_weights = [
        0.020, 0.012, 0.008, 0.006, 0.006, 0.010, 0.020, 0.035,
        0.050, 0.055, 0.055, 0.050, 0.055, 0.060, 0.060, 0.060,
        0.065, 0.075, 0.090, 0.100, 0.095, 0.070, 0.045, 0.030,
    ]
    start = datetime(2025, 11, 1, 0, 0, 0)
    rows: list[list[object]] = []

    for event_id in range(1, N_TELECOM_EVENTS + 1):
        tower_id = weighted(rng, list(zip(tower_ids, tower_weights)))
        # A small number of malformed records exercises the quality gate.
        if rng.random() < 0.004:
            tower_id = ""
        event_type = weighted(rng, EVENT_TYPES)
        technology = tower_tech.get(tower_id, "4G")
        ts = random_ts(rng, start, 7, hour_weights)
        customer_id = f"CUST-{rng.randint(1, 8000):06d}"
        plan_type = weighted(rng, TELECOM_PLANS)
        device_type = weighted(rng, TELECOM_DEVICES)

        if event_type == "data":
            duration = rng.randint(60, 7_200)
            bytes_total = int(rng.uniform(5, 900) * 1024 * 1024)
            base_latency = 18 if technology == "5G" else 34
            latency = max(4, int(rng.gauss(base_latency, 9)))
        elif event_type == "voice":
            duration = rng.randint(20, 1_800)
            bytes_total = 0
            latency = 0
        else:
            duration = 0
            bytes_total = rng.randint(40, 1_400)
            latency = 0

        # Congestion is higher in the evening and on the hot cell.
        evening = 1.0 if 17 <= ts.hour <= 22 else 0.0
        tower_load = 0.18 if tower_id == "TWR-001" else 0.08 if tower_id == "TWR-002" else 0.0
        prb = 32 + 38 * evening + 25 * tower_load + rng.gauss(0, 9)
        prb = max(5, min(99, round(prb, 1)))

        drop_probability = 0.004
        if technology == "4G":
            drop_probability += 0.004
        if tower_id == "TWR-001":
            drop_probability += 0.018
        if prb > 85:
            drop_probability += 0.010
        dropped = 1 if rng.random() < drop_probability else 0

        throughput = round(bytes_total * 8 / max(duration, 1) / 1_000_000, 2) if event_type == "data" else 0.0

        rows.append([
            f"EVT-{event_id:08d}",
            ts.strftime("%Y-%m-%d %H:%M:%S"),
            customer_id,
            tower_id,
            tower_region.get(tower_id, ""),
            technology,
            event_type,
            duration,
            bytes_total,
            latency,
            throughput,
            prb,
            dropped,
            plan_type,
            device_type,
        ])

    rows.sort(key=lambda row: row[1])
    write_csv(
        out / "telecom" / "network_events.csv",
        [
            "event_id", "event_ts", "customer_id", "tower_id", "region",
            "technology", "event_type", "duration_sec", "bytes_total",
            "latency_ms", "throughput_mbps", "prb_utilization", "dropped",
            "plan_type", "device_type",
        ],
        rows,
    )


