# Fraud: synthetic card transactions with labelled patterns
# ---------------------------------------------------------------------------

MERCHANTS = [
    ("M-001", "Nile Grocers", "grocery", "low", "Egypt"),
    ("M-002", "Cairo Electronics", "electronics", "medium", "Egypt"),
    ("M-003", "Skyline Travel", "travel", "high", "UAE"),
    ("M-004", "Pixel Games", "digital", "high", "USA"),
    ("M-005", "City Fuel", "fuel", "low", "Egypt"),
    ("M-006", "Harbor Fashion", "fashion", "medium", "Egypt"),
    ("M-007", "Atlas Marketplace", "marketplace", "medium", "UK"),
    ("M-008", "Metro ATM", "atm", "low", "Egypt"),
    ("M-009", "Cloud Tools", "software", "medium", "Germany"),
    ("M-010", "Golden Restaurants", "restaurant", "low", "Egypt"),
    ("M-011", "Global Duty Free", "travel", "high", "France"),
    ("M-012", "Quick Digital", "digital", "high", "USA"),
]

FRAUD_PATTERNS = ["card_testing", "account_takeover", "unusual_geo"]


def generate_fraud(rng: random.Random, out: Path) -> None:
    write_csv(
        out / "fraud" / "merchants.csv",
        ["merchant_id", "merchant_name", "category", "risk_tier", "country"],
        [list(m) for m in MERCHANTS],
    )

    cards = [(f"CARD-{i:06d}", f"CUST-{rng.randint(1, 5000):06d}", rng.choice(["Egypt", "UAE", "KSA", "USA", "Germany", "UK"])) for i in range(1, 6_001)]
    merchants_by_category: dict[str, list[tuple]] = {}
    for merchant in MERCHANTS:
        merchants_by_category.setdefault(merchant[2], []).append(merchant)

    start = datetime(2025, 10, 15, 0, 0, 0)
    business_hours = [
        0.012, 0.008, 0.006, 0.005, 0.006, 0.010, 0.020, 0.040,
        0.060, 0.070, 0.075, 0.070, 0.070, 0.070, 0.070, 0.070,
        0.070, 0.075, 0.085, 0.080, 0.065, 0.045, 0.030, 0.020,
    ]
    rows: list[dict] = []
    used_ids = 0

    def next_id() -> str:
        nonlocal used_ids
        used_ids += 1
        return f"TXN-{used_ids:08d}"

    # Normal activity.
    for _ in range(N_TRANSACTIONS - N_FRAUD):
        card_id, customer_id, home_country = rng.choice(cards)
        channel = weighted(rng, [("online", 0.44), ("pos", 0.46), ("atm", 0.10)])
        if channel == "atm":
            category = "atm"
            amount = round(rng.uniform(20, 500), 2)
        else:
            category = weighted(rng, [
                ("grocery", 0.20), ("restaurant", 0.16), ("fuel", 0.12),
                ("fashion", 0.13), ("electronics", 0.10), ("travel", 0.08),
                ("digital", 0.09), ("marketplace", 0.07), ("software", 0.05),
            ])
            amount = round(min(2_500, max(1, rng.lognormvariate(3.7, 1.0))), 2)
        merchant = rng.choice(merchants_by_category[category])
        country = home_country if rng.random() < 0.93 else rng.choice([m[4] for m in MERCHANTS])
        ip_country = country if rng.random() < 0.94 else rng.choice(["USA", "UAE", "Germany", "UK"])
        ts = random_ts(rng, start, 30, business_hours)
        device_id = f"DEV-{customer_id[-4:]}-{rng.randint(1, 3):02d}"
        rows.append({
            "transaction_id": next_id(),
            "customer_id": customer_id,
            "card_id": card_id,
            "merchant_id": merchant[0],
            "merchant_category": merchant[2],
            "amount": amount,
            "currency": "USD",
            "channel": channel,
            "country": country,
            "ip_country": ip_country,
            "device_id": device_id,
            "event_ts": ts,
            "is_fraud": 0,
            "fraud_pattern": "",
        })

    # Pattern 1: card testing. 20 cards, 10 tiny online charges each, in minutes.
    for _ in range(20):
        card_id, customer_id, _ = rng.choice(cards)
        merchant = rng.choice(merchants_by_category["digital"])
        base = random_ts(rng, start, 30)
        base = base.replace(hour=rng.choice([1, 2, 3, 4, 22, 23]))
        for offset in range(10):
            rows.append({
                "transaction_id": next_id(),
                "customer_id": customer_id,
                "card_id": card_id,
                "merchant_id": merchant[0],
                "merchant_category": merchant[2],
                "amount": round(rng.uniform(0.50, 4.99), 2),
                "currency": "USD",
                "channel": "online",
                "country": "USA",
                "ip_country": "USA",
                "device_id": f"DEV-NEW-{rng.randint(1000, 9999)}",
                "event_ts": base + timedelta(seconds=offset * rng.randint(20, 90)),
                "is_fraud": 1,
                "fraud_pattern": "card_testing",
            })

    # Pattern 2: account takeover. Large online purchases, new device, foreign IP.
    for _ in range(200):
        card_id, customer_id, _ = rng.choice(cards)
        merchant = rng.choice(merchants_by_category[weighted(rng, [("electronics", 0.45), ("travel", 0.35), ("digital", 0.20)])])
        ts = random_ts(rng, start, 30)
        rows.append({
            "transaction_id": next_id(),
            "customer_id": customer_id,
            "card_id": card_id,
            "merchant_id": merchant[0],
            "merchant_category": merchant[2],
            "amount": round(rng.uniform(700, 4_000), 2),
            "currency": "USD",
            "channel": "online",
            "country": "USA" if rng.random() < 0.7 else "UAE",
            "ip_country": "USA",
            "device_id": f"DEV-NEW-{rng.randint(1000, 9999)}",
            "event_ts": ts,
            "is_fraud": 1,
            "fraud_pattern": "account_takeover",
        })

    # Pattern 3: unusual geography. A physical card suddenly appears abroad.
    for _ in range(200):
        card_id, customer_id, _ = rng.choice(cards)
        merchant = rng.choice(merchants_by_category[weighted(rng, [("travel", 0.4), ("fashion", 0.3), ("electronics", 0.3)])])
        ts = random_ts(rng, start, 30)
        rows.append({
            "transaction_id": next_id(),
            "customer_id": customer_id,
            "card_id": card_id,
            "merchant_id": merchant[0],
            "merchant_category": merchant[2],
            "amount": round(rng.uniform(300, 2_500), 2),
            "currency": "USD",
            "channel": "pos",
            "country": "France" if rng.random() < 0.6 else "UAE",
            "ip_country": "Egypt",
            "device_id": f"DEV-{customer_id[-4:]}-{rng.randint(1, 3):02d}",
            "event_ts": ts,
            "is_fraud": 1,
            "fraud_pattern": "unusual_geo",
        })

    # Keep exactly the target count if rounding produced extra rows.
    fraud_rows = [row for row in rows if row["is_fraud"] == 1]
    if len(fraud_rows) > N_FRAUD:
        keep = {id(row) for row in rng.sample(fraud_rows, N_FRAUD)}
        rows = [row for row in rows if row["is_fraud"] == 0 or id(row) in keep]
    elif len(fraud_rows) < N_FRAUD:
        raise RuntimeError("fraud generator produced fewer rows than expected")

    rows.sort(key=lambda row: row["event_ts"])
    for index, row in enumerate(rows, start=1):
        row["transaction_id"] = f"TXN-{index:08d}"
    write_csv(
        out / "fraud" / "transactions.csv",
        [
            "transaction_id", "customer_id", "card_id", "merchant_id",
            "merchant_category", "amount", "currency", "channel", "country",
            "ip_country", "device_id", "event_ts", "is_fraud", "fraud_pattern",
        ],
        [[row[key] for key in (
            "transaction_id", "customer_id", "card_id", "merchant_id",
            "merchant_category", "amount", "currency", "channel", "country",
            "ip_country", "device_id", "event_ts", "is_fraud", "fraud_pattern",
        )] for row in rows],
    )


