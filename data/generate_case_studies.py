# Logistics: hub network and parcel shipments
# ---------------------------------------------------------------------------

HUBS = [
    ("HUB-CAI", "Cairo", "Cairo", "Egypt", 30.0444, 31.2357),
    ("HUB-ALX", "Alexandria", "Alexandria", "Egypt", 31.2001, 29.9187),
    ("HUB-GIZ", "Giza", "Cairo", "Egypt", 29.9792, 31.1342),
    ("HUB-MNS", "Mansoura", "Delta", "Egypt", 31.0409, 31.3785),
    ("HUB-ASW", "Aswan", "Upper Egypt", "Egypt", 24.0889, 32.8998),
    ("HUB-LXR", "Luxor", "Upper Egypt", "Egypt", 25.6872, 32.6396),
    ("HUB-DXB", "Dubai", "Gulf", "UAE", 25.2048, 55.2708),
    ("HUB-RUH", "Riyadh", "Gulf", "KSA", 24.7136, 46.6753),
    ("HUB-FRA", "Frankfurt", "Europe", "Germany", 50.1109, 8.6821),
    ("HUB-LHR", "London", "Europe", "UK", 51.5074, -0.1278),
]
CARRIERS = [
    ("NileExpress", 0.91, 0.95),
    ("SwiftLine", 0.84, 1.02),
    ("GlobalFreight", 0.76, 1.08),
    ("MetroParcel", 0.87, 0.99),
]
SERVICE_LEVELS = [("Economy", 5, 7, 0.22), ("Standard", 3, 5, 0.52), ("Express", 1, 2, 0.26)]


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    radius = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2) ** 2
    return 2 * radius * math.asin(math.sqrt(a))


def generate_logistics(rng: random.Random, out: Path) -> None:
    write_csv(
        out / "logistics" / "hubs.csv",
        ["hub_id", "city", "region", "country", "latitude", "longitude"],
        [list(h) for h in HUBS],
    )
    hub_by_id = {h[0]: h for h in HUBS}
    hub_ids = [h[0] for h in HUBS]
    start = datetime(2025, 9, 1, 0, 0, 0)
    rows: list[list[object]] = []

    for shipment_id in range(1, N_SHIPMENTS + 1):
        origin = rng.choice(hub_ids)
        destination = rng.choice([h for h in hub_ids if h != origin])
        o, d = hub_by_id[origin], hub_by_id[destination]
        distance = haversine_km(o[4], o[5], d[4], d[5])
        carrier, on_time_rate, speed_factor = rng.choice(CARRIERS)
        service, min_days, max_days, _ = rng.choices(SERVICE_LEVELS, weights=[s[3] for s in SERVICE_LEVELS], k=1)[0]
        ship_ts = random_ts(rng, start, 60)
        promised_days = rng.randint(min_days, max_days)
        promised_ts = ship_ts + timedelta(days=promised_days, hours=rng.randint(0, 8))

        # Most shipments arrive within the promise; carrier quality shifts the tail.
        if rng.random() < on_time_rate:
            transit_days = rng.uniform(0.6, promised_days * 0.95)
        else:
            transit_days = rng.uniform(promised_days * 1.02, promised_days + 4.0)
        transit_days *= speed_factor
        delivered_ts = ship_ts + timedelta(days=transit_days, hours=rng.randint(0, 10))

        status = weighted(rng, [("Delivered", 0.92), ("In Transit", 0.04), ("Exception", 0.02), ("Returned", 0.02)])
        delivered_value: datetime | None = delivered_ts if status == "Delivered" else None
        if status == "Returned":
            delivered_value = delivered_ts

        weight = round(max(0.1, min(50, rng.lognormvariate(1.1, 0.8))), 2)
        if rng.random() < 0.003:
            weight = 0.0  # malformed record for the quality gate
        cost = round(4.5 + distance * 0.012 + weight * 0.55 + {"Economy": 0, "Standard": 2.5, "Express": 6.0}[service] + rng.uniform(0, 3), 2)

        rows.append([
            f"SHP-{shipment_id:07d}",
            origin,
            destination,
            carrier,
            service,
            ship_ts.strftime("%Y-%m-%d %H:%M:%S"),
            promised_ts.strftime("%Y-%m-%d %H:%M:%S"),
            delivered_value.strftime("%Y-%m-%d %H:%M:%S") if delivered_value else "",
            status,
            weight,
            cost,
            round(distance, 1),
            d[2],
        ])

    write_csv(
        out / "logistics" / "shipments.csv",
        [
            "shipment_id", "origin_hub", "destination_hub", "carrier",
            "service_level", "ship_ts", "promised_ts", "delivered_ts",
            "status", "weight_kg", "cost_usd", "distance_km", "customer_region",
        ],
        rows,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent / "case_studies")
    args = parser.parse_args()
    out = args.output
    rng = random.Random(SEED)

    generate_telecom(rng, out)
    generate_fraud(rng, out)
    generate_logistics(rng, out)

    print(f"Generated case-study data under {out}:")
    print(f"  telecom/towers.csv          {len(TOWERS):,} rows")
    print(f"  telecom/network_events.csv  {N_TELECOM_EVENTS:,} rows")
    print(f"  fraud/merchants.csv         {len(MERCHANTS):,} rows")
    print(f"  fraud/transactions.csv      {N_TRANSACTIONS:,} rows ({N_FRAUD:,} labelled synthetic fraud)")
    print(f"  logistics/hubs.csv          {len(HUBS):,} rows")
    print(f"  logistics/shipments.csv     {N_SHIPMENTS:,} rows")
    print("\nAll records are synthetic. Fraud labels exist only to evaluate teaching rules.")


if __name__ == "__main__":
    main()
